const MAX_BUFFERED_CHARS = 1_048_576;


// Extracts top-level JSON objects from a stream that may interleave them with
// non-JSON noise (progress bars, banners) and split them across chunks. Prose
// holds braces too ("template {model} is unset"), so a candidate object is
// abandoned as soon as it stops looking like JSON: a `{` must be followed by a
// key or `}`, and a string cannot hold a raw line break. Otherwise one stray
// brace would nest every later event until the buffer cap dropped them all.
function makeEventScanner(onObject) {
  let buf = "";
  let index = 0;
  let depth = 0;
  let start = -1;
  let inString = false;
  let escaped = false;
  let expectKey = false;
  const abandon = () => {
    depth = 0;
    start = -1;
    inString = false;
    escaped = false;
    expectKey = false;
  };
  return (chunk) => {
    if (!chunk) return;
    buf += chunk;
    for (;;) {
      while (index < buf.length) {
        const ch = buf[index];
        // Only track strings inside an object (depth > 0). At depth 0 we are
        // skipping a junk prefix, and an unmatched `"` there must not swallow the
        // real `{...}` that follows in the same chunk.
        if (inString) {
          if (escaped) escaped = false;
          else if (ch === "\\") escaped = true;
          else if (ch === '"') inString = false;
          else if (ch === "\n" || ch === "\r") abandon();
          index += 1;
          continue;
        }
        if (expectKey && ch !== " " && ch !== "\t" && ch !== "\n" && ch !== "\r") {
          expectKey = false;
          if (ch !== '"' && ch !== "}") {
            // Not an object after all: rescan this character at depth 0.
            abandon();
            continue;
          }
        }
        if (ch === '"') {
          if (depth > 0) inString = true;
        } else if (ch === "{") {
          if (depth === 0) start = index;
          depth += 1;
          expectKey = true;
        } else if (ch === "}") {
          if (depth > 0) {
            depth -= 1;
            if (depth === 0 && start !== -1) {
              const slice = buf.slice(start, index + 1);
              start = -1;
              let parsed;
              try { parsed = JSON.parse(slice); } catch { parsed = undefined; /* skip malformed */ }
              if (parsed !== undefined) onObject(parsed);
            }
          }
        }
        index += 1;
      }
      if (depth === 0 || start === -1 || buf.length - start <= MAX_BUFFERED_CHARS) break;
      // A complete object may exceed the retained-input cap within this chunk.
      // Drop only an oversized partial, then rescan its suffix so a later
      // concatenated event is not lost.
      buf = buf.slice(start + MAX_BUFFERED_CHARS);
      index = 0;
      abandon();
    }
    if (depth > 0 && start !== -1) {
      if (start > 0) {
        buf = buf.slice(start);
        index -= start;
        start = 0;
      }
    } else {
      buf = "";
      index = 0;
      start = -1;
    }
  };
}

// ---- src/adapters/kimi.mjs

const MAX_BRIEF_BYTES = (process.platform === "win32" ? 12 : 120) * 1024;


const kimi = {
  key: "kimi",
  versionField: "kimiVersion",
  defaults: { timeout: "30m", model: null, session: null },
  flags: {
    "--model": { key: "model" },
    "--session": { key: "session" },
    "--resume-last": { key: "resumeLast", kind: "bool" },
    "--add-dir": { key: "addDirs", kind: "list" },
  },
  validate(opts) {
    exclusive(opts, [["resumeLast", "session", "--resume-last and --session are mutually exclusive; pass only one"]]);
    // kimi resolves a relative --add-dir against ITS cwd, so resolve against
    // --cd, which may appear after --add-dir on the command line.
    opts.addDirs = opts.addDirs.map((dir) => resolve(opts.cd, dir));
  },
  maxBriefBytes: MAX_BRIEF_BYTES,
  briefTooLarge: (kb) => `brief is ${kb}KB; kimi passes the prompt as a CLI argument, which the OS caps (~128KB on Linux, 32K characters for the whole command line on Windows). Trim it, or have kimi read large context from the workspace instead of inlining it.`,
  state: () => ({ text: [] }),
  fields: (opts) => ({
    model: opts.model,
    resumed: Boolean(opts.resumeLast || opts.session),
  }),
  version: () => ({ launch: { command: "kimi", args: ["--version"] } }),
  unavailableHint: "Install Kimi Code and run `kimi login`.",
  launch(opts, brief) {
    const args = ["--output-format", "stream-json"];
    if (opts.model) args.push("-m", opts.model);
    if (opts.session) args.push("--session", opts.session);
    else if (opts.resumeLast) args.push("--continue");
    for (const dir of opts.addDirs) args.push("--add-dir", dir);
    // --prompt=<brief>, not ["--prompt", brief]: the equals form binds a brief
    // that starts with "-" instead of letting it parse as a flag.
    args.push(`--prompt=${brief}`);
    return { command: "kimi", args };
  },
  scanner: makeEventScanner,
  onEvent(event, state) {
    if (event.role === "assistant" && typeof event.content === "string") state.text.push(event.content);
    if (event.role === "meta" && event.type === "session.resume_hint" && typeof event.session_id === "string") {
      state.sessionId = event.session_id;
    }
  },
  final: (state) => state.text.join("\n\n"),
};


await runRelay(kimi);
